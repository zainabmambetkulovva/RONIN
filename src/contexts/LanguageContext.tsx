export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>("ru");

  // Load from localStorage
  useEffect(() => {
    const saved = localStorage.getItem("ronin-language") as Language;
    if (saved && (saved === "ru" || saved === "en" || saved === "ky")) {
      setLanguageState(saved);
    }
  }, []);

  // Атрибут lang нужен скринридерам и для правильных переносов слов
  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem("ronin-language", lang);
  };

  const t = (key: string): string => {
    const landing = landingTranslations[language] as Record<string, string>;
    const cabinet = cabinetTranslations[language] as Record<string, string>;
    return landing[key] || cabinet[key] || translations[language][key as keyof typeof translations.ru] || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within LanguageProvider");
  }
  return context;
}
